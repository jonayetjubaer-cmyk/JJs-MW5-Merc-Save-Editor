"""MW5 pilot persona / portrait / dialogue voice catalog (loader).

The data lives in `pilot_catalog.json.gz` (Scarab's format) and loads through
catalog_source -- from an active external Scarab folder if one is configured,
otherwise the built-in bundle. It is optional: folders generated by an older
Scarab have no pilot catalog, and the pickers then fall back to whatever
portraits and voices the loaded save already uses.

A pilot's look is three linked assets: a portrait (MWPortraitAsset), a dialogue
voice (MWDialogueVoiceAsset) and, for scripted characters, a persona
(MWPersonaAsset) that ties them to a name, bio and tags. Sex is not stored on a
pilot; personas carry `Persona.Sex.Male/Female` tags, so portraits and voices
inherit it from the personas that use them (and from their names otherwise).
"""
import re
from collections import Counter

import catalog_source

_d = catalog_source.load_catalog("pilot_catalog") or {}

PERSONAS = list(_d.get("personas", []))
PORTRAITS = list(_d.get("portraits", []))
VOICES = list(_d.get("voices", []))

MALE, FEMALE = "Male", "Female"
SEX_FILTERS = ("All", MALE, FEMALE)

# Personas a player can actually meet as a pilot (rather than enemy commanders,
# templates, employers or crew).
_HIREABLE_TAGS = {
    "Persona.Use.Employable",
    "PilotPersona.Use.Lancemate",
    "PilotPersona.Use.Hero",
    "Persona.Use.FriendlyPilot",
    "PilotPersona.Use.FriendlyPilot",
}
_SEP = " -- "


def persona_sex(persona: dict) -> str | None:
    tags = persona.get("attributes") or []
    if "Persona.Sex.Female" in tags:
        return FEMALE
    if "Persona.Sex.Male" in tags:
        return MALE
    return None


def sex_from_name(name: str) -> str | None:
    lower = name.casefold()
    if "female" in lower:      # check first: "female" contains "male"
        return FEMALE
    if "male" in lower:
        return MALE
    return None


def _persona_sex_guess(persona: dict) -> str | None:
    """The sex tag, else whatever the persona's own voice / portrait names say."""
    return (persona_sex(persona)
            or sex_from_name(persona.get("voice") or "")
            or sex_from_name(persona.get("portrait") or ""))


def _sex_map(field: str) -> dict[str, str]:
    found: dict[str, set[str]] = {}
    for persona in PERSONAS:
        sex, name = _persona_sex_guess(persona), persona.get(field)
        if sex and name:
            found.setdefault(name, set()).add(sex)
    # A portrait or voice shared by both sexes stays unknown.
    return {name: next(iter(sexes)) for name, sexes in found.items() if len(sexes) == 1}


_PORTRAIT_SEX = _sex_map("portrait")
_VOICE_SEX = _sex_map("voice")


def portrait_sex(name: str) -> str | None:
    return _PORTRAIT_SEX.get(name) or sex_from_name(name)


def voice_sex(name: str) -> str | None:
    return _VOICE_SEX.get(name) or sex_from_name(name)


def asset_choices(save_names, catalog, sex_of, sex: str = "All") -> list[str]:
    """Sorted asset names from the catalog plus those the save already uses.
    A sex filter drops assets known to be the other sex; unknown stay listed."""
    names = {n for n in set(save_names) | set(catalog) if n and n != "None"}
    if sex in (MALE, FEMALE):
        names = {n for n in names if sex_of(n) in (sex, None)}
    return sorted(names, key=str.casefold)


def _split_camel(text: str) -> str:
    text = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", " ", text)
    return text.replace("_", " ").strip()


def is_readable(text: str | None) -> bool:
    """False for empty text and for unresolved string-table keys
    (`Persona_Character_..._FullName`); a single resolved word ("Raptor") is fine."""
    return bool(text and text.strip()) and not text.startswith("Persona_")


def is_readable_bio(text: str | None) -> bool:
    """A bio is prose; a lone identifier-like token is an asset name or key, not text."""
    return is_readable(text) and (
        " " in text.strip() or not re.fullmatch(r"[A-Za-z0-9_]+", text.strip()))


def _name_from_key(key: str | None) -> str | None:
    """'Persona_Character_LyanaMoore_FullName' -> 'Lyana Moore'."""
    if not key:
        return None
    m = re.fullmatch(r"Persona_(?:Character|Generic)_(.+?)_(?:FullName|Callsign)(?:_.*)?", key)
    return _split_camel(m.group(1)) if m else None


def persona_name(persona: dict) -> str:
    """Best human-readable name: resolved text, a name derived from the string
    key, then the asset name."""
    for field in ("full_name", "callsign"):
        value = persona.get(field)
        if is_readable(value):
            return value.strip()
    for field in ("full_name", "callsign"):
        derived = _name_from_key(persona.get(field))
        if derived:
            return derived
    return _split_camel(persona.get("asset_name", ""))


def persona_callsign(persona: dict) -> str:
    """A persona's callsign as readable text, falling back to its name."""
    value = persona.get("callsign")
    if is_readable(value):
        return value.strip()
    return _name_from_key(value) or persona_name(persona)


def persona_bio_parts(persona: dict) -> list[str] | None:
    """The persona's bio as [bio, bio1, bio2] ("{name}" placeholders kept: the
    game fills them in), or None when the persona has no bio text."""
    parts = [persona.get(key) or "" for key in ("bio", "bio1", "bio2")]
    parts = [p if is_readable_bio(p) else "" for p in parts]
    return parts if any(parts) else None


def has_name(persona: dict) -> bool:
    """True if the persona carries a real name (templates only have asset names)."""
    return any(is_readable(persona.get(f)) or _name_from_key(persona.get(f))
               for f in ("full_name", "callsign"))


def is_hireable(persona: dict) -> bool:
    return bool(_HIREABLE_TAGS.intersection(persona.get("attributes") or []))


def persona_display(persona: dict) -> str:
    """'Lyana Moore -- Lyana': readable name, then the asset it came from."""
    return f"{persona_name(persona)}{_SEP}{persona['asset_name']}"


def persona_choices(hireable_only: bool = True) -> list[str]:
    rows = [p for p in PERSONAS if not hireable_only or is_hireable(p)]
    return sorted((persona_display(p) for p in rows), key=str.casefold)


def find_persona(text: str) -> dict | None:
    """A dropdown display string (or a bare asset name) -> its persona."""
    asset = text.rsplit(_SEP, 1)[-1].strip()
    for persona in PERSONAS:
        if persona["asset_name"] == asset:
            return persona
    return None


# -- "who uses this" labels for the portrait / voice pickers -------------------
_MAX_USERS_SHOWN = 2
_MAX_NAME_REPEATS = 3   # a name on more personas than this is a placeholder


def _rank(persona: dict) -> int:
    """Sort key for naming a voice's users: lancemates and heroes, then other
    hireable pilots, then the rest."""
    tags = set(persona.get("attributes") or [])
    if tags & {"PilotPersona.Use.Hero", "PilotPersona.Use.Lancemate"}:
        return 0
    return 1 if is_hireable(persona) else 2


def _users_by_asset(field: str) -> dict[str, list[str]]:
    """asset name -> names of the personas that use it. Named, hireable
    characters come first; templates and crew without a real name are left out."""
    named = [p for p in PERSONAS if has_name(p)]
    # Placeholder names ("AI PILOT", "Lt. Major") repeat across many personas
    # and say nothing about a voice; only distinctive names are useful.
    seen = Counter(persona_name(p) for p in named)
    rows: dict[str, list[tuple[int, str]]] = {}
    for persona in named:
        asset = persona.get(field)
        name = persona_name(persona)
        if asset and seen[name] <= _MAX_NAME_REPEATS:
            rows.setdefault(asset, []).append((_rank(persona), name))
    users = {}
    for asset, found in rows.items():
        names = []
        for _, name in sorted(found, key=lambda row: (row[0], row[1].casefold())):
            if name not in names:
                names.append(name)
        users[asset] = names
    return users


_PORTRAIT_USERS = _users_by_asset("portrait")
_VOICE_USERS = _users_by_asset("voice")


def _labelled(asset: str, users: dict[str, list[str]]) -> str:
    names = [n for n in users.get(asset, []) if n.casefold() != asset.casefold()]
    if not names:
        return asset
    shown = ", ".join(names[:_MAX_USERS_SHOWN])
    more = len(names) - _MAX_USERS_SHOWN
    return f"{asset}{_SEP}{shown}" + (f" (+{more})" if more > 0 else "")


def portrait_display(asset: str) -> str:
    """'LeonFreeman -- Leon Freeman': the asset, then who usually uses it."""
    return _labelled(asset, _PORTRAIT_USERS)


def voice_display(asset: str) -> str:
    return _labelled(asset, _VOICE_USERS)


def resolve_asset(text: str) -> str:
    """A picker display string (or a bare typed name) -> the asset name."""
    return text.split(_SEP, 1)[0].strip()
